// npm run afoqt:audit-all [-- --n=100 --write]
//
// The question-engine quality bar (see .claude/skills/question-engine-quality/SKILL.md) applied to EVERY topic in EVERY
// subtest, so "is this section filled out?" is answered with numbers instead of a feeling.
//
// For each topic (concept id) it deals a 100-question run through the same builder the drill screen uses and measures:
//   * distinct stems out of 100        a run that cannot reach 100 distinct questions repeats itself
//   * variants reported / distinct     generators that report `variant` can be spread and measured; the rest are a blind spot
//   * share of the most common variant one kind filling the run is "the same question again"
//   * generators with thin phrasing    a generator whose 60 draws use <= 3 sentence frames
//   * declared item space (stemSpace)  a generator that can only ever make a few dozen questions
// and ranks the topics by how weak they are. `--write` saves the scoreboard to docs/afoqt/ENGINE-AUDIT.md.
import fs from 'node:fs';
import '../src/pages/theknowledgebase/afoqt/templates/index.js';
import { buildDrill, allTemplates, generateInstance } from '../src/pages/theknowledgebase/afoqt/engine/generator.js';
import { mulberry32 } from '../src/pages/theknowledgebase/engine/rng.js';

const arg = (k, d = null) => { const hit = process.argv.find((a) => a.startsWith(`--${k}=`)); return hit ? hit.slice(k.length + 3) : d; };
const N = Number(arg('n', 100));
const write = process.argv.includes('--write');
const skeleton = (s) => String(s).replace(/-?\d+(\.\d+)?/g, '#').replace(/\b[A-Z]\b/g, 'L').replace(/\s+/g, ' ');

// concept -> generators (non-stretch)
const byConcept = new Map();
for (const t of allTemplates()) {
  if (t.stretch) continue;
  for (const c of t.concepts ?? []) { if (!byConcept.has(c)) byConcept.set(c, []); byConcept.get(c).push(t); }
}

const thinCache = new Map();
function thinPhrasing(t) {
  if (thinCache.has(t.id)) return thinCache.get(t.id);
  const sk = new Set();
  for (let i = 1; i <= 60; i++) { try { const q = generateInstance(t.id, i * 7919); if (q) sk.add(skeleton(q.stem)); } catch { /* a failing draw is reported by selftest, not here */ } }
  const thin = sk.size <= 3;
  thinCache.set(t.id, thin);
  return thin;
}

const rows = [];
for (const [concept, gens] of byConcept) {
  const subtest = gens[0].subtest;
  // A figure-based subtest (a shared grid, pile, passage or dial pair) is run 25-40 questions at a time on shared figures,
  // so a 100-question topic run is not the meaningful test there: judge those at 25.
  const runN = gens.some((g) => g.sheet) ? Math.min(N, 25) : N;
  let qs = [];
  try { qs = buildDrill({ subtest, count: runN, rng: mulberry32(1), distinct: true, filter: (t) => (t.concepts ?? []).includes(concept) }); } catch (e) { qs = []; }
  const stems = new Set(qs.map((q) => q.stem));
  const reporting = gens.filter((g) => qs.some((q) => q.templateId === g.id && q.variant)).length;
  const vcount = new Map();
  for (const q of qs) if (q.variant) { const k = `${q.templateId}|${q.variant}`; vcount.set(k, (vcount.get(k) ?? 0) + 1); }
  const top = vcount.size ? Math.max(...vcount.values()) : 0;
  const thin = gens.filter(thinPhrasing).length;
  const capped = gens.filter((g) => g.stemSpace && g.stemSpace < runN).length;
  const flags = [];
  if (gens.length < 3) flags.push(`only ${gens.length} generator${gens.length === 1 ? '' : 's'}`);
  if (stems.size < runN || qs.length < runN) flags.push(`${stems.size}/${runN} distinct`);
  if (top > Math.max(6, N * 0.12) && vcount.size) flags.push(`one variant fills ${top}`);
  if (thin) flags.push(`${thin} generator${thin === 1 ? '' : 's'} with thin phrasing`);
  if (capped) flags.push(`${capped} capped below ${runN}`);
  // weakness score: higher = worse. Distinctness and capped item spaces matter most, then breadth, then measurability.
  const score = (qs.length < runN ? 40 : 0) + (runN - stems.size) * 2 + capped * 15 + (gens.length < 3 ? 25 : gens.length < 5 ? 10 : 0)
    + (reporting < gens.length ? 3 : 0) + thin * 6 + (top > Math.max(6, N * 0.12) ? 10 : 0);
  rows.push({ concept, subtest, runN, gens: gens.length, distinct: stems.size, dealt: qs.length, variants: vcount.size, reporting, top, thin, capped, flags, score });
}

const bySub = new Map();
for (const r of rows) { if (!bySub.has(r.subtest)) bySub.set(r.subtest, []); bySub.get(r.subtest).push(r); }
const lines = [];
lines.push(`# Engine audit: every topic, ${N}-question runs`, '', `Generated by \`npm run afoqt:audit-all -- --write\`. Bar: \`.claude/skills/question-engine-quality/SKILL.md\`.`, '',
  '| Subtest | Topics | Generators | Topics that CANNOT deal a full run of distinct questions | Topics with thin phrasing | Topics that pass every hard check | Generators that report variants |', '|---|---|---|---|---|---|---|');
for (const [sub, rs] of [...bySub.entries()].sort()) {
  const gens = new Set(rs.flatMap((r) => byConcept.get(r.concept).map((g) => g.id)));
  const allG = [...gens].map((id) => allTemplates().find((t) => t.id === id));
  const withVar = allG.filter((g) => rs.some((r) => byConcept.get(r.concept).includes(g) && r.reporting > 0 && (() => { try { return !!generateInstance(g.id, 7919)?.variant; } catch { return false; } })())).length;
  const clean = rs.filter((r) => r.flags.length === 0).length;
  const short = rs.filter((r) => r.distinct < r.runN).length;
  const thinTopics = rs.filter((r) => r.thin > 0).length;
  lines.push(`| ${sub} | ${rs.length} | ${gens.size} | ${short} | ${thinTopics} | ${clean} | ${withVar} of ${gens.size} |`);
}
lines.push('', 'Hard checks: a full run of distinct questions (100, or 25 for figure-based subtests), at least 3 generators, no declared item space smaller than the run, no generator with 3 or fewer sentence frames, no single variant filling the run. "Variants seen: unmeasured" means the generators do not report a variant yet, so how varied they are cannot be counted; that is the next gap everywhere outside Math Knowledge and the new work-problem family.');
lines.push('', '## Weakest topics first', '', '| Topic | Subtest | Generators | Distinct in 100 | Variants seen | Problems |', '|---|---|---|---|---|---|');
for (const r of rows.sort((a, b) => b.score - a.score).filter((r) => r.flags.length).slice(0, 60)) {
  lines.push(`| ${r.concept} | ${r.subtest} | ${r.gens} | ${r.distinct}/${r.runN} | ${r.variants || 'unmeasured'} | ${r.flags.join('; ')} |`);
}
const clean = rows.filter((r) => r.flags.length === 0);
lines.push('', `## Topics that pass every check (${clean.length})`, '', clean.map((r) => `${r.concept} (${r.subtest})`).join(', ') || '(none yet)');

const out = lines.join('\n');
console.log(out.split('\n').slice(0, 14).join('\n'));
console.log(`\n... ${rows.length} topics audited; ${rows.filter((r) => r.flags.length).length} need work; ${clean.length} pass every check.`);
console.log('\nTen weakest:');
for (const r of rows.sort((a, b) => b.score - a.score).slice(0, 10)) console.log(`  ${r.subtest.padEnd(3)} ${r.concept.padEnd(34)} ${r.gens} gen, ${r.distinct}/${r.dealt} distinct, ${r.variants || 'unmeasured'} variants | ${r.flags.join('; ')}`);
if (write) {
  fs.writeFileSync('src/pages/theknowledgebase/docs/afoqt/ENGINE-AUDIT.md', out + '\n');
  console.log('\nWrote src/pages/theknowledgebase/docs/afoqt/ENGINE-AUDIT.md');
}
