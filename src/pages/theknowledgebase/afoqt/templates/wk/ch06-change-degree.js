//
// Three fields that overlap constantly on the real subtest: words for something growing,
// shrinking, starting, stopping or transforming; words for size, extent, intensity or scarcity;
// and words for approving, condemning, praising or dismissing. A candidate who knows one word in
// a cluster is often one step from knowing three - burgeon/wane/abate all describe a curve moving,
// they just disagree about which direction and how fast.
//
// EVERY ROW DECLARES ITS OWN FOUR WRONG OPTIONS. See engine/words.js for why they cannot be
// drawn from other rows - English has too many near-synonyms for a blind draw to be safe, and a
// second correct answer is invisible to every structural check. The four are named error modes:
// the confusable's meaning, the opposite, a same-field word that is not the meaning, and a
// same-register decoy.
//
// AUTHORING RULES, enforced by registerWords() and worth knowing before adding a row:
//   - all five options must be the same part of speech as the headword; a lone noun among four
//     adjectives is findable without knowing what any of them mean
//   - no option may contain the headword or share a six-character prefix with it
//   - `related` must NOT be a synonym. It is the option that punishes step 5 of the official
//     method - "choose the best synonym, not just a related word" - so it has to be genuinely
//     close and genuinely wrong
//   - the confusable must be a real sound-alike or look-alike that people actually mix up

