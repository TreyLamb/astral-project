  'requiring that system. Adding up every aircraft that is merely present, without checking these statuses, produces',
  'a number that looks reassuring on paper and means very little in practice.',
  '',
  'Spare parts availability drives this rate more than almost any other factor. A single missing part',
  'can ground an aircraft that is otherwise flightworthy, and older aircraft often depend on parts that',
  'are no longer produced in quantity. Maintenance crews sometimes remove a working part from one aircraft',
  'to fix another, a practice called cannibalization, which keeps one jet flying while quietly grounding a',
  'second one. A fleet can therefore look adequately sized while actually running on borrowed components that',
  'shift the true readiness problem from plane to plane.',
  '',
  'Aircraft age changes the picture in a less obvious way as well. Newer airframes typically need',
  'less scheduled maintenance time per flying hour, while aging airframes require inspections that grow more frequent',
  'and more thorough with each passing year. A fleet of older aircraft can require nearly the',
  'same number of maintenance hours as a much larger fleet of new ones, which means the',
  "mission capable rate tends to decline over an airframe's service life even without any single dramatic failure.",
  '',
  'Because of all this, defense planners treat the mission capable rate as one of the clearest',
  'early warning signs of a fleet in trouble. A steady decline in the rate, even a',
